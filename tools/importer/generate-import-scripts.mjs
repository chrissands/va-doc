/**
 * Generates one import script per template (tools/importer/import-<template>.js)
 * from page-templates.json, embedding the template object as PAGE_TEMPLATE.
 * Usage: node tools/importer/generate-import-scripts.mjs [templateName]
 */
import { readFileSync, writeFileSync, readdirSync } from 'fs';
import { dirname, join } from 'path';
import { fileURLToPath } from 'url';

const dir = dirname(fileURLToPath(import.meta.url));
const { templates } = JSON.parse(readFileSync(join(dir, 'page-templates.json'), 'utf8'));
const only = process.argv[2];
const transformers = readdirSync(join(dir, 'transformers')).filter((f) => f.endsWith('.js')).sort();
const camel = (s) => s.replace(/-([a-z])/g, (_, c) => c.toUpperCase());

templates.filter((t) => !only || t.name === only).forEach((t) => {
  const parserNames = [...new Set(t.blocks.map((b) => b.name))];
  parserNames.forEach((n) => readFileSync(join(dir, 'parsers', `${n}.js`)));
  const tName = (f) => `${camel(f.replace('.js', ''))}Transformer`;
  const src = `/* eslint-disable */
/* global WebImporter */
// Generated by generate-import-scripts.mjs from page-templates.json — template "${t.name}".
${parserNames.map((n) => `import ${camel(n)}Parser from './parsers/${n}.js';`).join('\n')}
${transformers.map((f) => `import ${tName(f)} from './transformers/${f}';`).join('\n')}

const PAGE_TEMPLATE = ${JSON.stringify(t, null, 2)};

const parsers = {
${parserNames.map((n) => `  '${n}': ${camel(n)}Parser,`).join('\n')}
};

// cleanup must run before sections, metadata last
const transformers = [${['cleanup.js', 'sections.js', 'metadata.js'].filter((f) => transformers.includes(f)).concat(transformers.filter((f) => !['cleanup.js', 'sections.js', 'metadata.js'].includes(f))).map(tName).join(', ')}];

function executeTransformers(hookName, element, payload) {
  const enhancedPayload = { ...payload, template: PAGE_TEMPLATE };
  transformers.forEach((fn) => {
    try { fn(hookName, element, enhancedPayload); } catch (e) { console.error(\`Transformer failed at \${hookName}:\`, e); }
  });
}

function findBlocksOnPage(document, template) {
  const pageBlocks = [];
  template.blocks.forEach((blockDef) => {
    blockDef.instances.forEach((selector) => {
      document.querySelectorAll(selector).forEach((element) => {
        pageBlocks.push({ name: blockDef.name, selector, element });
      });
    });
  });
  return pageBlocks;
}

function targetPath(url) {
  const u = new URL(url);
  if (PAGE_TEMPLATE.paths && PAGE_TEMPLATE.paths[u.search]) return PAGE_TEMPLATE.paths[u.search];
  if (PAGE_TEMPLATE.pathPattern) {
    return PAGE_TEMPLATE.pathPattern.replace(/\\{(\\w+)\\}/g, (_, k) => (u.searchParams.get(k) || '').toLowerCase());
  }
  return PAGE_TEMPLATE.path;
}

export default {
  // Give every placeholder link a unique href before the importer runs: it merges adjacent
  // links that share an href, which would collapse "#"-linked menus into one link.
  preprocess: ({ document }) => {
    document.querySelectorAll('a[href="#"], a:not([href])').forEach((a, i) => a.setAttribute('href', '#placeholder-' + i));
  },

  transform: (payload) => {
    const { document, url, params } = payload;
    const main = document.body;

    executeTransformers('beforeTransform', main, payload);

    const pageBlocks = findBlocksOnPage(document, PAGE_TEMPLATE);
    pageBlocks.forEach((block) => {
      if (!block.element.parentNode) return;
      const parser = parsers[block.name];
      if (!parser) return;
      try { parser(block.element, { document, url, params }); } catch (e) { console.error(\`Failed to parse \${block.name} (\${block.selector}):\`, e); }
    });

    executeTransformers('afterTransform', main, payload);

    WebImporter.rules.transformBackgroundImages(main, document);
    WebImporter.rules.adjustImageUrls(main, url, params.originalURL);

    const path = WebImporter.FileUtils.sanitizePath(targetPath(params.originalURL));
    return [{
      element: main,
      path,
      report: { title: document.title, template: PAGE_TEMPLATE.name, blocks: pageBlocks.map((b) => b.name) },
    }];
  },
};
`;
  writeFileSync(join(dir, `import-${t.name}.js`), src);
  console.log(`wrote import-${t.name}.js`);
});
